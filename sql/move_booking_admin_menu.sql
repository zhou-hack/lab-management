-- 需求：管理端侧栏「设备使用审批」（219，/admin/equipment/bookings）
--       由顶级入口改为「设备管理」的子菜单。
-- 父菜单按 route_path='/admin/equipment' 定位（不同库编号不同：
--       本机库为 163，规范种子为 210，故不硬编码 id）。
-- 前端 SidebarItem 已支持「虚拟子菜单（设备库存/设备台账）+ 数据库子菜单」
-- 合并渲染，挂载后侧栏结构：设备管理 → 设备库存 / 设备台账 / 设备使用审批。
-- 动态路由不受影响（AdminLayout 子路由按绝对 path 平级注册）。
-- 幂等：仅当 219 仍挂 NULL 根时更新，重复执行无副作用。
-- ============================================================================
SET NAMES utf8mb4;

UPDATE sys_menu m
JOIN sys_menu p ON p.route_path = '/admin/equipment' AND p.deleted = 0
SET m.parent_id = p.id
WHERE m.id = 219 AND m.parent_id IS NULL;
